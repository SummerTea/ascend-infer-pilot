"""Code generation from parsed structs and config."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .naming import camel_to_snake
from .parser import FieldDef, StructDef

GENERATED_HEADER = "// DO NOT EDIT - generated by atb-bindgen\n"

TEMPLATE_DIR = Path(__file__).parent / "templates"


def _default_value(field: FieldDef, struct: StructDef, config: dict[str, Any]) -> str:
    overrides = config.get("init_overrides", {}).get(struct.name, {})
    field_overrides = config.get("field_overrides", {})
    key = f"{struct.name}.{field.name}"
    if field.default:
        d = field.default.strip()
        if d == "{}":
            return "py::list()" if field.is_svector or field.is_vector else "{}"
        if d == "nullptr":
            return "nullptr"
        if d in ("true", "false"):
            return d
        if re.match(r'^".*"$', d):
            return d
        if re.match(r"^-?\d+(\.\d+)?f?$", d) or re.match(r"^-?\d+e-?\d+", d, re.I):
            return d
        if "::" in d:
            return d
        return d
    if field.is_svector or field.is_vector:
        return "py::list()"
    if field.cpp_type in config.get("opaque_pointer_types", []):
        return "nullptr"
    type_defaults = {
        "bool": "false",
        "int": "0",
        "int32_t": "0",
        "int64_t": "0",
        "uint32_t": "0",
        "uint64_t": "0",
        "float": "0.0f",
        "double": "0.0",
        "std::string": '""',
    }
    base = field.cpp_type.replace("const ", "").replace(" &", "").replace("*", "").strip()
    if base in type_defaults:
        return type_defaults[base]
    if base in ("aclDataType", "aclFormat"):
        return f"{base}::ACL_DT_UNDEFINED" if base == "aclDataType" else "ACL_FORMAT_UNDEFINED"
    if base == "CommMode":
        return "CommMode::COMM_MULTI_PROCESS"
    if base == "InputLayout":
        return "InputLayout::TYPE_BSND"
    if base == "QuantType":
        return "QuantType::QUANT_UNQUANT"
    if base == "DynamicQuantType":
        return "DynamicQuantType::DYNAMIC_QUANT_UNDEFINED"
    for ns in config.get("namespace_enums", []):
        if base == ns:
            return f"{ns}::{_first_enum_value(base)}"
    for ne in struct.nested_enums:
        if ne.name == base or field.cpp_type.endswith(ne.name):
            if ne.values:
                v = ne.values[0].name
                return f"{struct.name}::{ne.name}::{v}"
    for ns in struct.nested_structs:
        if ns.name == base or field.cpp_type == ns.name:
            return f"{struct.name}::{ns.name}()"
    return f"{base}()"


def _first_enum_value(enum_name: str) -> str:
    defaults = {
        "InputLayout": "TYPE_BSND",
        "QuantType": "QUANT_UNQUANT",
        "DynamicQuantType": "DYNAMIC_QUANT_UNDEFINED",
        "ActivationType": "ACTIVATION_UNDEFINED",
        "CommMode": "COMM_MULTI_PROCESS",
    }
    return defaults.get(enum_name, "UNDEFINED")


def _field_binding_mode(field: FieldDef, struct: StructDef, config: dict[str, Any]) -> str:
    key = f"{struct.name}.{field.name}"
    fo = config.get("field_overrides", {}).get(key, {})
    if fo.get("binding") == "svector_property_only":
        return "svector_property"
    if field.is_svector:
        return "svector_property"
    if field.is_vector:
        return "readwrite"
    return "readwrite"


def _qualify_type(struct: StructDef) -> str:
    if struct.namespace == "atb::infer":
        return struct.name
    return f"atb::{struct.name}" if struct.namespace == "atb" else struct.name


def _cpp_ns_prefix(struct: StructDef) -> str:
    if struct.namespace == "atb":
        return "atb::"
    if struct.namespace == "atb::infer":
        return "atb::infer::"
    return ""


class CodeGenerator:
    def __init__(self, config: dict[str, Any]):
        self.config = config
        self.env = Environment(
            loader=FileSystemLoader(str(TEMPLATE_DIR)),
            autoescape=select_autoescape(enabled_extensions=()),
            trim_blocks=True,
            lstrip_blocks=True,
            keep_trailing_newline=True,
        )
        self.env.filters["snake"] = camel_to_snake

    def generate_operation_inits(self) -> str:
        ops = self.config.get("operation_ops", [])
        lines = [GENERATED_HEADER]
        for op in ops:
            if op == "GraphParam":
                lines.append("        .def(py::init<const atb::GraphParam &>())")
            else:
                lines.append(f"        .def(py::init<const {op} &>())")
        return "\n".join(lines) + "\n"

    def generate_builder_add_nodes(self) -> str:
        ops = self.config.get("graph_builder_ops", [])
        skip = set(self.config.get("skip_ops_in_graphbuilder", []))
        lines = [GENERATED_HEADER]
        for op in ops:
            if op in skip:
                continue
            lines.append(
                f'        .def("add_node", py::overload_cast<const std::vector<std::string> &, '
                f"const atb::infer::{op} &>(&TorchAtb::GraphBuilder::AddNode))"
            )
        return "\n".join(lines) + "\n"

    def generate_wrapper_declarations(self) -> str:
        ops = self.config.get("operation_ops", [])
        lines = [GENERATED_HEADER]
        for op in ops:
            if op == "GraphParam":
                lines.append(f"    explicit OperationWrapper(const atb::GraphParam &param);")
            else:
                lines.append(f"    explicit OperationWrapper(const atb::infer::{op} &param);")
        return "\n".join(lines) + "\n"

    def generate_wrapper_impls(self) -> str:
        ops = self.config.get("operation_ops", [])
        blocks = [GENERATED_HEADER.rstrip()]
        for op in ops:
            if op == "GraphParam":
                blocks.append(
                    "OperationWrapper::OperationWrapper(const atb::GraphParam &param)\n"
                    "{\n    CreateOpUniquePtr(param);\n}"
                )
            else:
                blocks.append(
                    f"OperationWrapper::OperationWrapper(const {op} &param)\n"
                    "{\n    CreateOpUniquePtr(param);\n}"
                )
        return "\n\n".join(blocks) + "\n"

    def generate_graph_builder_decls(self) -> str:
        ops = self.config.get("graph_builder_ops", [])
        skip = set(self.config.get("skip_ops_in_graphbuilder", []))
        lines = [GENERATED_HEADER]
        for op in ops:
            if op in skip:
                continue
            lines.append(
                f"    GraphNode &AddNode(const std::vector<std::string> &inputs, "
                f"const atb::infer::{op} &param);"
            )
        return "\n".join(lines) + "\n"

    def generate_graph_builder_impls(self) -> str:
        ops = self.config.get("graph_builder_ops", [])
        skip = set(self.config.get("skip_ops_in_graphbuilder", []))
        blocks = [GENERATED_HEADER.rstrip()]
        for op in ops:
            if op in skip:
                continue
            blocks.append(
                f"GraphNode &GraphBuilder::AddNode(const std::vector<std::string> &inputs, "
                f"const atb::infer::{op} &param)\n"
                "{\n    return AddNodeByParamType(inputs, param);\n}"
            )
        return "\n\n".join(blocks) + "\n"

    def generate_param_bindings(self, structs: dict[str, StructDef]) -> str:
        """Generate bindings_ops.inc from parsed structs (param class bindings only)."""
        skip_param_class = {"GraphParam"}
        parts = [GENERATED_HEADER.rstrip()]
        for op_name in self.config.get("whitelist", []):
            if op_name in skip_param_class:
                continue
            if op_name not in structs:
                print(f"[WARN] No parsed struct for {op_name}, skipping param binding")
                continue
            sd = structs[op_name]
            init_override = self.config.get("init_overrides", {}).get(op_name, {})
            if init_override.get("init_style") == "preserve":
                continue
            ctx = {
                "struct": sd,
                "config": self.config,
                "default_value": lambda f, s=sd: _default_value(f, s, self.config),
                "binding_mode": lambda f, s=sd: _field_binding_mode(f, s, self.config),
                "qualify": _qualify_type,
                "cpp_ns": _cpp_ns_prefix,
            }
            tmpl = self.env.get_template("bindings_ops.inc.j2")
            parts.append(tmpl.render(**ctx))
        return "\n\n".join(parts) + "\n"

    def write_all(
        self,
        output_dir: Path,
        structs: dict[str, StructDef],
        *,
        param_bindings: str | None = None,
    ) -> dict[str, Path]:
        output_dir.mkdir(parents=True, exist_ok=True)
        files = {
            "bindings_ops.inc": param_bindings or self.generate_param_bindings(structs),
            "bindings_operation_inits.inc": self.generate_operation_inits(),
            "bindings_builder_add_nodes.inc": self.generate_builder_add_nodes(),
            "operation_wrapper_generated.inc": self.generate_wrapper_declarations(),
            "operation_wrapper_ops.inc": self.generate_wrapper_impls(),
            "enger_graph_builder_generated.inc": self.generate_graph_builder_decls(),
            "enger_graph_builder_ops.inc": self.generate_graph_builder_impls(),
        }
        written = {}
        for name, content in files.items():
            path = output_dir / name
            path.write_text(content, encoding="utf-8")
            written[name] = path
        return written
