"""Bootstrap: extract generated sections from hand-written source files."""

from __future__ import annotations

import re
from pathlib import Path

GENERATED_HEADER = "// DO NOT EDIT - generated by atb-bindgen\n"


def _extract_between(text: str, start_marker: str, end_marker: str) -> str:
    start = text.find(start_marker)
    if start == -1:
        raise ValueError(f"Start marker not found: {start_marker!r}")
    end = text.find(end_marker, start + len(start_marker))
    if end == -1:
        raise ValueError(f"End marker not found: {end_marker!r}")
    return text[start:end].rstrip() + "\n"


def extract_bindings_ops(bindings_cpp: Path) -> str:
    text = bindings_cpp.read_text(encoding="utf-8")
    marker_start = "    py::class_<LayerNormParam>"
    marker_end = "\n}"
    start = text.find(marker_start)
    if start == -1:
        raise ValueError("Cannot find param bindings start in bindings.cpp")
    end = text.rfind(marker_end)
    if end == -1 or end <= start:
        raise ValueError("Cannot find param bindings end in bindings.cpp")
    body = text[start:end].rstrip() + "\n"
    return GENERATED_HEADER + body


def extract_operation_inits(bindings_cpp: Path) -> list[str]:
    text = bindings_cpp.read_text(encoding="utf-8")
    pattern = re.compile(r"\.def\(py::init<const (\w+) &>\(\)\)")
    return pattern.findall(text)


def extract_wrapper_declarations(wrapper_h: Path) -> str:
    text = wrapper_h.read_text(encoding="utf-8")
    lines = []
    for line in text.splitlines():
        m = re.match(r"\s+explicit OperationWrapper\(const atb::(?:infer::)?(\w+) &param\);", line)
        if m:
            lines.append(line.strip())
    if not lines:
        raise ValueError("No wrapper declarations found")
    return GENERATED_HEADER + "\n".join(f"    {l}" for l in lines) + "\n"


def extract_wrapper_impls(wrapper_cpp: Path) -> str:
    text = wrapper_cpp.read_text(encoding="utf-8")
    pattern = re.compile(
        r"(OperationWrapper::OperationWrapper\(const \w+ &param\)\s*\{[^}]+\})",
        re.MULTILINE,
    )
    blocks = pattern.findall(text)
    if not blocks:
        raise ValueError("No wrapper implementations found")
    return GENERATED_HEADER + "\n\n".join(blocks) + "\n"


def extract_graph_builder_decls(graph_h: Path) -> str:
    text = graph_h.read_text(encoding="utf-8")
    lines = []
    for line in text.splitlines():
        m = re.match(
            r"\s+GraphNode &AddNode\(const std::vector<std::string> &inputs, const atb::infer::(\w+) &param\);",
            line,
        )
        if m:
            lines.append(line.strip())
    if not lines:
        raise ValueError("No graph builder declarations found")
    return GENERATED_HEADER + "\n".join(f"    {l}" for l in lines) + "\n"


def extract_graph_builder_impls(graph_cpp: Path) -> str:
    text = graph_cpp.read_text(encoding="utf-8")
    pattern = re.compile(
        r"(GraphNode &GraphBuilder::AddNode\(const std::vector<std::string> &inputs, "
        r"const atb::infer::\w+ &param\)\s*\{[^}]+\})",
        re.MULTILINE,
    )
    blocks = pattern.findall(text)
    if not blocks:
        raise ValueError("No graph builder implementations found")
    return GENERATED_HEADER + "\n\n".join(blocks) + "\n"


def bootstrap_all(repo: Path, output_dir: Path) -> dict[str, Path]:
    torch_atb = repo / "src/torch_atb"
    bindings = torch_atb / "bindings.cpp"
    outputs = {
        "bindings_ops.inc": output_dir / "bindings_ops.inc",
        "operation_wrapper_generated.inc": output_dir / "operation_wrapper_generated.inc",
        "operation_wrapper_ops.inc": output_dir / "operation_wrapper_ops.inc",
        "enger_graph_builder_generated.inc": output_dir / "enger_graph_builder_generated.inc",
        "enger_graph_builder_ops.inc": output_dir / "enger_graph_builder_ops.inc",
    }
    outputs["bindings_ops.inc"].write_text(extract_bindings_ops(bindings), encoding="utf-8")
    outputs["operation_wrapper_generated.inc"].write_text(
        extract_wrapper_declarations(torch_atb / "operation_wrapper.h"), encoding="utf-8"
    )
    outputs["operation_wrapper_ops.inc"].write_text(
        extract_wrapper_impls(torch_atb / "operation_wrapper.cpp"), encoding="utf-8"
    )
    outputs["enger_graph_builder_generated.inc"].write_text(
        extract_graph_builder_decls(torch_atb / "enger_graph_builder.h"), encoding="utf-8"
    )
    outputs["enger_graph_builder_ops.inc"].write_text(
        extract_graph_builder_impls(torch_atb / "enger_graph_builder.cpp"), encoding="utf-8"
    )
    return outputs
