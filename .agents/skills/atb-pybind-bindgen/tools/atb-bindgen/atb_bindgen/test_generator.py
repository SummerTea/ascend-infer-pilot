"""Test case generator for ATB pybind bindings."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .golden_recipes import get_manual_stub, get_recipe
from .naming import param_to_op_snake
from .parser import StructDef

TEMPLATE_DIR = Path(__file__).parent / "templates"
MARKER = "# DO NOT EDIT - generated by atb-bindgen"
GENERATED_TEST_SUFFIX = "_bindgen_test.py"
LEGACY_STUB_SUFFIX = "_generated_test.py"


class TestGenerator:
    def __init__(self, config: dict[str, Any], atb_repo: Path, *, force: bool = False):
        self.config = config
        self.atb_repo = atb_repo
        self.force = force
        self.env = Environment(
            loader=FileSystemLoader(str(TEMPLATE_DIR)),
            autoescape=select_autoescape(enabled_extensions=()),
            trim_blocks=True,
            lstrip_blocks=True,
        )

    def _test_dir(self) -> Path:
        return self.atb_repo / self.config["test_output_dir"]

    def _param_test_file(self) -> Path:
        return self.atb_repo / self.config["op_param_test_file"]

    def generate_param_test_entries(self, structs: dict[str, StructDef]) -> str:
        lines = []
        tmpl = self.env.get_template("op_param_test.inc.j2")
        for op_name in self.config.get("whitelist", []):
            if op_name == "GraphParam":
                continue
            if op_name not in structs:
                continue
            lines.append(
                tmpl.render(param_name=op_name, op_snake=param_to_op_snake(op_name)).rstrip()
            )
        return "\n\n".join(lines)

    def append_param_tests(self, structs: dict[str, StructDef]) -> Path:
        path = self._param_test_file()
        if not path.exists():
            raise FileNotFoundError(f"op_param_test.py not found: {path}")

        content = path.read_text(encoding="utf-8")
        if MARKER in content:
            content = content[: content.index(MARKER)].rstrip() + "\n"

        tmpl = self.env.get_template("op_param_test.inc.j2")
        blocks = []
        for op_name in self.config.get("whitelist", []):
            if op_name == "GraphParam" or op_name not in structs:
                continue
            raw = tmpl.render(param_name=op_name, op_snake=param_to_op_snake(op_name)).strip()
            blocks.append(self._indent_block(raw, 4))
        entries = "\n\n".join(blocks)
        new_content = (
            content.rstrip()
            + f"\n\n{MARKER}\n\n"
            + "class TestGeneratedParams(unittest.TestCase):\n"
            + entries
            + "\n"
        )
        path.write_text(new_content, encoding="utf-8")
        return path

    @staticmethod
    def _indent_block(text: str, spaces: int) -> str:
        pad = " " * spaces
        return "\n".join(pad + line if line.strip() else line for line in text.splitlines())

    def _resolve_test_content(self, param_name: str, mapping: dict[str, Any]) -> str | None:
        category = mapping.get("category", "skip_npu")
        if category in ("comm_skip", "skip_npu"):
            return None
        op_snake = param_to_op_snake(param_name)
        if category in ("torch_builtin", "torch_compose"):
            recipe = get_recipe(param_name)
            if recipe:
                return recipe
            print(f"[WARN] No built-in recipe for {param_name}, skipping forward test")
            return None
        if category == "custom_manual":
            return get_manual_stub(param_name, op_snake)
        return None

    def generate_forward_tests(self) -> list[Path]:
        written: list[Path] = []
        golden = self.config.get("golden_mappings", {})
        for param_name, mapping in golden.items():
            content = self._resolve_test_content(param_name, mapping)
            if content is None:
                continue
            op_snake = param_to_op_snake(param_name)
            out_dir = self._test_dir() / op_snake
            out_dir.mkdir(parents=True, exist_ok=True)
            init_py = out_dir / "__init__.py"
            if not init_py.exists():
                init_py.touch()
            out_path = out_dir / f"{op_snake}{GENERATED_TEST_SUFFIX}"
            legacy = out_dir / f"{op_snake}{LEGACY_STUB_SUFFIX}"
            if legacy.exists():
                legacy.unlink()
            if out_path.exists() and not self.force:
                continue
            out_path.write_text(content, encoding="utf-8")
            written.append(out_path)
            print(f"[OK] forward test {out_path} ({mapping.get('category')})")
        return written

    def generate_all(self, structs: dict[str, StructDef]) -> dict[str, Path]:
        result: dict[str, Path] = {}
        result["op_param_test.py"] = self.append_param_tests(structs)
        for p in self.generate_forward_tests():
            result[p.name] = p
        return result
